import DigestionInsightsEngine
import Foundation

/// Renders Simulation/results.md from results.json and checks that the
/// engine's `Thresholds.default` carries the calibrated values.
public enum Report {
    public struct Mismatch: Error, CustomStringConvertible {
        public var description: String
    }

    public static func run(paths: SimulationPaths, checkOnly: Bool, log: @escaping @Sendable (String) -> Void) throws {
        let results = try JSONDecoder().decode(SimulationResults.self, from: Data(contentsOf: paths.resultsJSON))
        try checkThresholds(results)
        let markdown = render(results)
        if checkOnly {
            let existing = try String(contentsOf: paths.resultsMarkdown, encoding: .utf8)
            guard existing == markdown else {
                throw Mismatch(description: "results.md is out of date; run `digestion-sim report`")
            }
            log("report: results.md matches results.json")
        } else {
            try markdown.write(to: paths.resultsMarkdown, atomically: true, encoding: .utf8)
            log("report: wrote \(paths.resultsMarkdown.path)")
        }
        log(results.headline.sentence)
    }

    static func checkThresholds(_ results: SimulationResults) throws {
        let t = Thresholds.default
        let c = results.calibration
        guard t.earlyProb == c.earlyProb, t.clearProb == c.clearProb, t.halfProb == c.halfProb else {
            throw Mismatch(description: "Thresholds.default (\(t.earlyProb), \(t.clearProb), \(t.halfProb)) differs from results.json (\(c.earlyProb), \(c.clearProb), \(c.halfProb))")
        }
    }

    static func pct(_ p: Proportion) -> String {
        guard p.trials > 0 else { return "–" }
        return String(format: "%.1f %% (%ld/%ld; %.1f–%.1f)", 100 * p.rate, p.successes, p.trials, 100 * p.lower, 100 * p.upper)
    }

    static func short(_ p: Proportion) -> String {
        guard p.trials > 0 else { return "–" }
        return String(format: "%.0f %% (%ld/%ld)", 100 * p.rate, p.successes, p.trials)
    }

    static func number(_ value: Double?, _ format: String = "%.1f") -> String {
        guard let value, value.isFinite else { return "–" }
        return String(format: format, value)
    }

    static func food(_ id: String) -> String {
        String(id.split(separator: ":").last ?? Substring(id))
    }

    static func effect(_ e: Double) -> String {
        e == e.rounded() ? String(format: "×%.0f", e) : String(format: "×%.1f", e)
    }

    public static func render(_ r: SimulationResults) -> String {
        var md: [String] = []
        let c = r.calibration
        let s = r.settings
        let horizons = s.horizons
        md.append("# Digestion Insights simulation results")
        md.append("")
        md.append("Generated by `swift run -c release --package-path Packages/DigestionInsights digestion-sim report` from `results.json`. Do not edit by hand; every number below comes from that file. Methods: `docs/digestion-insights-methodology.md`.")
        md.append("")
        md.append("## Headline")
        md.append("")
        md.append(r.headline.sentence)
        md.append("")
        md.append("- User expectation \"first evidence after about 2 weeks\": \(r.headline.expectationEarly).")
        md.append("- User expectation \"clear patterns after about 3 months\": \(r.headline.expectationClear).")
        md.append("")
        md.append("Typical logging, ×2 trigger, all lag windows, converged runs only (share of users; 95 % interval):")
        md.append("")
        md.append("| logged days | early signal or clear | clear pattern |")
        md.append("|---|---|---|")
        for (e, cl) in zip(r.headline.earlyShares, r.headline.clearShares) {
            md.append("| \(e.horizon) | \(pct(e.share)) | \(pct(cl.share)) |")
        }
        md.append("")

        md.append("## Calibrated thresholds")
        md.append("")
        md.append(String(format: "`Thresholds.default`: **earlyProb %.3f, clearProb %.3f, halfProb %.3f** (unit 3 placeholders: 0.90, 0.98, 0.90).", c.earlyProb, c.clearProb, c.halfProb))
        md.append("")
        md.append("Rule: earlyProb = smallest grid value (\(number(c.grid.first, "%.2f")) … \(number(c.grid.last, "%.3f"))) whose pooled null false-early rate is at most \(Int(c.falseEarlyTarget * 100)) %; halfProb = earlyProb; clearProb = smallest grid value ≥ earlyProb whose pooled null false-clear rate is at most \(Int(c.falseClearTarget * 100)) %. A null analysis counts as a false early signal when any food in it reaches earlySignal or clearPattern; as a false clear pattern when any food reaches clearPattern. Calibration ignores the convergence gate.")
        md.append("")
        md.append("| null false-positive rate (95 % Wilson interval) | early signal or clear | clear pattern |")
        md.append("|---|---|---|")
        md.append("| pooled over horizons (\(c.nullAnalyses) analyses of \(c.nullUsers) null users) | \(pct(c.falseEarlyPooled)) | \(pct(c.falseClearPooled)) |")
        for row in c.perHorizon {
            md.append("| \(row.horizon) logged days | \(pct(row.falseEarly)) | \(pct(row.falseClear)) |")
        }
        md.append("| converged runs only (what the app would show) | \(pct(c.falseEarlyShown)) | \(pct(c.falseClearShown)) |")
        md.append("| null user flagged in at least one of its \(horizons.count) analyses | \(pct(c.falseEarlyEver)) | \(pct(c.falseClearEver)) |")
        md.append("| planted users, foods other than trigger and partner | \(pct(c.backgroundFalseEarly)) | \(pct(c.backgroundFalseClear)) |")
        md.append("")
        md.append("Targets met on the pooled point estimates: **\(c.targetsMet ? "yes" : "no")**. The intervals show how far the study can resolve the targets; with \(c.nullAnalyses) null analyses a 1 % rate cannot be told apart from 0 % or from a few percent.")
        md.append("")
        md.append("<details><summary>Threshold curve (pooled null analyses)</summary>")
        md.append("")
        md.append("| threshold | false early (earlyProb = t) | false clear (clearProb = halfProb = earlyProb = t) |")
        md.append("|---|---|---|")
        for p in c.curve {
            md.append("| \(number(p.threshold, "%.3f")) | \(short(p.falseEarly)) | \(short(p.falseClearWithEqualHalf)) |")
        }
        md.append("")
        md.append("</details>")
        md.append("")

        md.append("## Convergence")
        md.append("")
        md.append("Gate (B9): max split-R̂ < 1.01, min bulk ESS ≥ 400, no divergences, in all three fits. Single attempt per analysis (B11 attempt 1: warmup \(s.analysisConfig.warmup), \(s.analysisConfig.samples) draws, 4 chains, target acceptance \(number(s.analysisConfig.targetAcceptance, "%.2f"))). Retries (B11 attempts 2–3) were not simulated.")
        md.append("")
        md.append("| logging | logged days | converged | any divergence | median max R̂ | median symptoms | median run (s) |")
        md.append("|---|---|---|---|---|---|---|")
        for row in r.convergence {
            md.append("| \(row.diligence.rawValue) | \(row.horizon) | \(short(row.converged)) | \(short(row.withDivergences)) | \(number(row.medianMaxRhat, "%.3f")) | \(number(row.medianSymptoms, "%.0f")) | \(number(row.medianSeconds, "%.0f")) |")
        }
        md.append("")

        md.append("## Recovery of planted triggers")
        md.append("")
        md.append("Read this first (study design caveats):")
        md.append("")
        for caveat in s.designCaveats { md.append("- \(caveat)") }
        md.append("")
        md.append("Expected extra symptoms of the trigger kind per exposure, average user: " + s.expectedExcessPerExposure.keys.sorted { a, b in
            let pa = a.split(separator: " "), pb = b.split(separator: " ")
            let ea = Double(pa[0].dropFirst()) ?? 0, eb = Double(pb[0].dropFirst()) ?? 0
            return ea != eb ? ea < eb : String(pa[1]) < String(pb[1])
        }.map { "\($0) \(number(s.expectedExcessPerExposure[$0], "%.2f"))" }.joined(separator: ", ") + ".")
        md.append("")
        md.append("Cell entries: early signal or clear / clear pattern, as counts of users, **ignoring** the convergence gate; in brackets the same counting only converged runs. n = users per cell. \"No link\" counts triggers wrongly reported as `noLinkFound`.")
        md.append("")
        var header = "| logging | effect | lag window | n |"
        var rule = "|---|---|---|---|"
        for h in horizons {
            header += " \(h) d |"
            rule += "---|"
        }
        header += " no link (all horizons) |"
        rule += "---|"
        md.append(header)
        md.append(rule)
        for d in LoggingDiligence.allCases {
            for e in Set(r.recovery.map(\.effect)).sorted() {
                for k in LagKernel.allCases {
                    let rows = r.recovery.filter { $0.diligence == d && $0.effect == e && $0.kernel == k }
                    guard let first = rows.first else { continue }
                    var line = "| \(d.rawValue) | \(effect(e)) | \(k.rawValue) \(number(k.hours.lowerBound, "%.0f"))–\(number(k.hours.upperBound, "%.0f")) h | \(first.counts.users) |"
                    for h in horizons {
                        if let x = rows.first(where: { $0.horizon == h })?.counts {
                            line += " \(x.early)/\(x.clear) [\(x.earlyShown)/\(x.clearShown)] |"
                        } else {
                            line += " – |"
                        }
                    }
                    line += " \(rows.reduce(0) { $0 + $1.counts.noLinkFound }) |"
                    md.append(line)
                }
            }
        }
        md.append("")
        md.append("By trigger food (all logging levels and lag windows), early signal or clear / clear, ignoring the gate:")
        md.append("")
        header = "| food | effect |"
        rule = "|---|---|"
        for h in horizons {
            header += " \(h) d |"
            rule += "---|"
        }
        md.append(header)
        md.append(rule)
        for f in s.triggerFoods {
            for e in Set(r.recoveryByFood.map(\.effect)).sorted() {
                let rows = r.recoveryByFood.filter { $0.food == f && $0.effect == e }
                guard !rows.isEmpty else { continue }
                var line = "| \(food(f)) | \(effect(e)) |"
                for h in horizons {
                    if let x = rows.first(where: { $0.horizon == h })?.counts {
                        line += " \(x.early)/\(x.clear) of \(x.users) |"
                    } else {
                        line += " – |"
                    }
                }
                md.append(line)
            }
        }
        md.append("")

        md.append("## Lag estimates")
        md.append("")
        md.append("Estimated `medianLagHours` (posterior median) minus the true median lag of the window, for triggers found (early or clear, ignoring the gate).")
        md.append("")
        md.append("| lag window | true median lag (h) | effect | logged days | found | median error (h) | median absolute error (h) |")
        md.append("|---|---|---|---|---|---|---|")
        for row in r.lagErrors where row.found > 0 {
            md.append("| \(row.kernel.rawValue) | \(number(row.trueMedianLag, "%.1f")) | \(effect(row.effect)) | \(row.horizon) | \(row.found) | \(number(row.medianError)) | \(number(row.medianAbsoluteError)) |")
        }
        md.append("")

        md.append("## Co-eaten partner")
        md.append("")
        md.append("Garlic triggers; onion is eaten with 85 % of garlic meals and is not a trigger. Share of garlic users where onion reaches a level (ignoring the gate), and where the engine lists onion in the trigger's `confoundedWith`.")
        md.append("")
        md.append("| logged days | onion early or clear | onion clear | onion early when garlic found | onion in `confoundedWith` |")
        md.append("|---|---|---|---|---|")
        for row in r.partner {
            md.append("| \(row.horizon) | \(short(row.partnerEarly)) | \(short(row.partnerClear)) | \(short(row.partnerEarlyWhenTriggerFound)) | \(short(row.flaggedAsConfounded)) |")
        }
        md.append("")

        md.append("## Alternative statistic (comparison only)")
        md.append("")
        md.append(String(format: "`probPeakAbove` (P(peak RR > %.2f)) with its own threshold %.3f, calibrated like earlyProb (null false-early %@). Users whose trigger is flagged, ignoring the gate. The level rules still use `probRaises`; switching is the user's decision.", s.analysisConfig.thresholds.noLinkUpper, r.peakAlternative.threshold, pct(r.peakAlternative.nullFalseEarly)))
        md.append("")
        md.append("| lag window | effect | logged days | n | via probRaises | via probPeakAbove |")
        md.append("|---|---|---|---|---|---|")
        for row in r.peakAlternative.rows {
            md.append("| \(row.kernel.rawValue) | \(effect(row.effect)) | \(row.horizon) | \(row.users) | \(row.earlyViaProbRaises) | \(row.earlyViaPeak) |")
        }
        md.append("")

        md.append("## Simulation-based calibration")
        md.append("")
        if let sbc = r.sbc, let plan = s.sbcPlan {
            md.append("Reduced model: \(plan.features.map(food).joined(separator: ", ")) (3 features), \(plan.kinds.count) kinds, \(plan.loggedDays) logged days of one synthetic meal log, production priors. \(sbc.replications) replications, warmup \(plan.warmup), \(plan.samples) draws × 4 chains, thinned to \(sbc.thinnedDraws) draws, ranks in \(sbc.bins) bins (Talts et al. 2018). Prior draws with an hourly rate above \(number(plan.maxHourlyRate, "%.0f")) were redrawn: \(sbc.redraws) redraws in total. Replications with divergences: \(sbc.replicationsWithDivergences). Median simulated symptoms per replication: \(number(sbc.medianSymptoms, "%.0f")).")
            md.append("")
            md.append("| quantity | rank histogram (\(sbc.bins) bins) | χ² (\(sbc.bins - 1) df) | p |")
            md.append("|---|---|---|---|")
            for q in sbc.quantities {
                md.append("| \(q.name) | \(q.histogram.map(String.init).joined(separator: " ")) | \(number(q.chiSquare)) | \(number(q.pValue, "%.3f")) |")
            }
            md.append("")
            md.append(String(format: "With %ld quantities, about %.1f p-values below 0.05 are expected by chance; Bonferroni level %.4f.", sbc.quantities.count, 0.05 * Double(sbc.quantities.count), 0.05 / Double(sbc.quantities.count)))
        } else {
            md.append("Not run.")
        }
        md.append("")

        md.append("## Settings")
        md.append("")
        md.append("- Engine: `AnalysisConfig` defaults (warmup \(s.analysisConfig.warmup), samples \(s.analysisConfig.samples), chains \(s.analysisConfig.chains), target acceptance \(number(s.analysisConfig.targetAcceptance, "%.2f")), max tree depth \(s.analysisConfig.maxTreeDepth), three fits), `ModelPriors.default` (slab \(number(s.analysisConfig.priors.slabScale, "%.1f"))), `chartDraws` 10 (chart data only).")
        md.append("- Users: \(s.plantedUsers) planted, \(s.nullUsers) null; \(s.analyses) analyses at \(horizons.map(String.init).joined(separator: ", ")) logged days. Kinds: \(s.kinds.joined(separator: ", ")). Foods (\(s.foods.count)): \(s.foods.map(food).joined(separator: ", ")).")
        md.append("- Planted effects ×1.5, ×2, ×4 (main grid) and ×10 (extension, typical logging); lag windows fast 1–4 h, medium 4–12 h, slow 24–60 h (box kernels).")
        for note in s.generatorNotes { md.append("- \(note).") }
        md.append("")
        md.append("Logging diligence (assumed, not measured):")
        md.append("")
        md.append("| logging | missed days | missed meals | missed symptoms | time SD (h) | late logs | late by up to (h) |")
        md.append("|---|---|---|---|---|---|---|")
        for d in LoggingDiligence.allCases {
            guard let p = s.diligence[d.rawValue] else { continue }
            md.append(String(format: "| %@ | %.0f %% | %.0f %% | %.0f %% | %.2f | %.0f %% | %.0f |", d.rawValue, 100 * p.missedDayRate, 100 * p.missedMealRate, 100 * p.missedSymptomRate, p.timeJitterHours, 100 * p.lateLogRate, p.lateLogMaxHours))
        }
        md.append("")
        md.append("Ingredient evidence per logged meal (assumed, not measured): " + s.evidence.keys.sorted().map { "\($0) \(number(s.evidence[$0], "%.2f"))" }.joined(separator: ", ") + ".")
        md.append("")

        md.append("## Compute")
        md.append("")
        md.append(String(format: "%@, %ld logical cores, `%@`, `VECLIB_MAXIMUM_THREADS=1`, several analyses in parallel. Wall time of the final runs: %.0f min.", r.compute.machine, r.compute.logicalCores, r.compute.build, r.compute.totalWallSeconds / 60))
        md.append("")
        for note in r.compute.notes { md.append("- \(note)") }
        md.append("")
        md.append("| run log | runs | wall time (min) |")
        md.append("|---|---|---|")
        for p in r.compute.phases {
            md.append(String(format: "| %@ | %ld | %.0f |", p.log, p.runs, p.wallSeconds / 60))
        }
        md.append("")
        return md.joined(separator: "\n")
    }
}
